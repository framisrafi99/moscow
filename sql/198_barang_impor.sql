-- 10/11/2026: daftar barang impor dari manajemen Moscow Supplies (file List Barang Impor).
-- asal: 'impor' = selalu impor (waktu tunggu ±105 hari); 'campuran' = kadang impor kadang lokal (baris kuning di file).
-- Barang jualan yang tidak ada di daftar ini = lokal / produksi sendiri.
-- Dipakai robot pengadaan (robot.js, md:pengadaan -> audit.pengadaan_robot) dan agen Penjaga bisnis / Asisten GM / Audit.
create table if not exists public.barang_impor (
  kode text primary key,
  nama text not null,
  asal text not null check (asal in ('impor','campuran')),
  catatan text,
  diubah timestamptz not null default now(),
  oleh text default 'manajemen Moscow Supplies'
);
alter table public.barang_impor enable row level security;
-- baca: semua yang punya peran (manajemen, kendali_bisnis, staf) dan robot hitung (header x-moscow-robot -> peran_saya() = manajemen)
create policy barang_impor_baca on public.barang_impor for select to anon, authenticated using (coalesce(public.peran_saya(), '') <> '');
create policy barang_impor_ubah on public.barang_impor for all to anon, authenticated using (public.peran_saya() = 'manajemen') with check (public.peran_saya() = 'manajemen');
grant select on public.barang_impor to anon, authenticated;
grant insert, update, delete on public.barang_impor to authenticated;
grant all on public.barang_impor to service_role;

